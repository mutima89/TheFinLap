"""Regenerate docs/CALCULATION_REFERENCE_GENERATED.md, docs/GLOSSARY.md and docs/MODEL_REFERENCE.md
from the app's own metadata.

Run from the project root:  python tools/gen_reference.py
The tables come from the calculation graph, the driver specifications and the KPI
definitions that the application itself uses, so they cannot drift from the code.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from aurelia import __version__  # noqa: E402
from aurelia.core.kpis import KPI_DEFINITIONS  # noqa: E402
from aurelia.model.assumptions import DRIVER_SPECS, baseline, get_path  # noqa: E402
from aurelia.model.engine import G, simulate  # noqa: E402


def _cell(s) -> str:
    return str(s).replace("|", "\\|").replace("\n", " ")


def main() -> Path:
    a = baseline()
    out = ["# Calculation and assumption reference (generated)", "",
           f"Generated by `tools/gen_reference.py` from Aurelia Finance Lab {__version__}. Do not edit by hand: the "
           "tables below are read from the same calculation graph, driver specifications and KPI definitions the "
           "application runs. All values are fictional training assumptions, not industry benchmarks.", ""]
    out += ["## 1. Calculation graph (evaluation order)", "",
            "Each node reads the line items listed under *Reads* and produces the line items in its table. "
            "Formulas are the plain-language formulas shown in the app's formula inspector.", ""]
    for n in G.order():
        out += [f"### Node `{n.name}` — {n.description}", "",
                f"Reads: {', '.join(f'`{d}`' for d in n.deps) or '(assumptions only)'}", "",
                "| Line item | Key | Formula | Unit | Assumptions read |", "|---|---|---|---|---|"]
        for li in n.outputs.values():
            out.append(f"| {_cell(li.label)} | `{li.key}` | {_cell(li.formula)} | {li.unit} | "
                       f"{', '.join(f'`{i}`' for i in li.inputs) or '—'} |")
        out.append("")
    out += ["## 2. Drivers (editable assumptions) and baseline values", "",
            "Every driver is validated against its range before a run; out-of-range input is rejected and the "
            "previous value kept.", "", "| Category | Driver | Path | Baseline | Unit | Allowed range | Meaning |",
            "|---|---|---|---|---|---|---|"]
    for s in sorted(DRIVER_SPECS, key=lambda d: (d.category, d.label)):
        try:
            v = get_path(a, s.path)
        except Exception:  # noqa: BLE001 – wildcard paths such as segments.*.x
            v = "(per segment)"
        out.append(f"| {s.category} | {_cell(s.label)} | `{s.path}` | {_cell(v)} | {s.unit} | "
                   f"{s.minimum} – {s.maximum} | {_cell(s.help or '')} |")
    out += ["", "## 3. KPI definitions", "", "| KPI | Formula | Unit | Better when | Notes |", "|---|---|---|---|---|"]
    for k in KPI_DEFINITIONS.values():
        out.append(f"| {k.name} | {_cell(k.formula)} | {k.unit} | {k.nature.replace('_', ' ')} | "
                   f"{_cell(k.description)} |")
    r = simulate(a)
    out += ["", "## 4. Integrity checks run on every simulation", "", "Tolerance SAR 0.01 per month.", "",
            "| Check | Rule | Baseline result |", "|---|---|---|"]
    for c in r.checks:
        out.append(f"| {c.name} | {_cell(c.detail)} | {'PASS' if c.passed else 'FAIL'} (max error {c.max_abs_error:.6f}) |")
    out.append("")
    p = ROOT / "docs" / "CALCULATION_REFERENCE_GENERATED.md"
    p.write_text("\n".join(out), encoding="utf-8")
    return p


def glossary() -> Path:
    from aurelia.learning.glossary import GLOSSARY, SHORTCUTS
    out = ["# Glossary", "", f"The same {len(GLOSSARY)} terms are searchable in the app (Glossary and Search, or Ctrl+K). "
           "Generated by `tools/gen_reference.py`. Figures quoted in definitions (VAT 15%, incentive fee 8%, "
           "materiality SAR 250k / 5%) are the simulator's fictional assumptions.", ""]
    for term, d in sorted(GLOSSARY.items(), key=lambda kv: kv[0].lower()):
        out += [f"**{term}** — {d}", ""]
    out += ["## Keyboard shortcuts", "", "| Keys | Action |", "|---|---|"]
    out += [f"| {k} | {v} |" for k, v in SHORTCUTS]
    p = ROOT / "docs" / "GLOSSARY.md"
    p.write_text("\n".join(out) + "\n", encoding="utf-8")
    return p


def model_reference() -> Path:
    from aurelia.analysis import decisions as D
    from aurelia.analysis import investment as inv
    from aurelia.learning.content import STAGES, topics
    from aurelia.learning.progress import COMPETENCIES
    from aurelia.model.assumptions import SEGMENTS, SEGMENT_LABELS, diff
    from aurelia.model.scenarios import SYSTEM_BUILDERS, SYSTEM_DESCRIPTIONS
    from aurelia.ui.pages.workbench import MODELS
    a = baseline()
    r = simulate(a)
    k = r.kpis(r.year_slice(1))
    o = ["# Model reference", "",
         "Generated by `tools/gen_reference.py` (prose and tables are rebuilt from the code). The hotel, the group, "
         "every figure and every event are fictional training material, not real data or benchmarks.", "",
         "## 1. The business", "",
         f"**{a['meta']['hotel_name']}** is a {a['rooms']['total_rooms']}-room luxury hotel owned by the fictional "
         f"**{a['meta']['group_name']}**. It has five room segments, a restaurant and bar, a spa, meetings and events, "
         "and ancillary income. The group is considering a second property, the fictional 80-room **Aurelia Oasis "
         "Resort**, modelled with the same engine.", "",
         f"Base case, model year 1 (FY2027): occupancy {k['occupancy'] * 100:.1f}%, ADR SAR {k['adr']:,.0f}, RevPAR "
         f"SAR {k['revpar']:,.0f}, total revenue SAR {k['total_revenue'] / 1e6:,.1f}m, GOP margin "
         f"{k['gop_margin'] * 100:.1f}%, EBITDA SAR {k['ebitda'] / 1e6:,.1f}m, closing cash SAR "
         f"{k['closing_cash'] / 1e6:,.1f}m.", "",
         "### Segments (Base case)", "",
         "| Segment | Published rate | Discount | Base demand / day | Price elasticity | Commission | Cancellation | "
         "No-show | Lead days | Cap / day |", "|---|---|---|---|---|---|---|---|---|---|"]
    for s_ in SEGMENTS:
        g = a["segments"][s_]
        o.append(f"| {SEGMENT_LABELS[s_]} | SAR {g['published_rate']:,.0f} | {g['discount_pct'] * 100:.0f}% | "
                 f"{g['base_demand']:.0f} | {g['elasticity']} | {g['commission_pct'] * 100:.1f}% | "
                 f"{g['cancellation_pct'] * 100:.0f}% | {g['no_show_pct'] * 100:.0f}% | {g['lead_days']} | "
                 f"{g['cap'] if g['cap'] is not None else '—'} |")
    o += ["", "## 2. Reference scenarios", "", "Protected; save changes under a new name.", "",
          "| Scenario | Description | Differences from Base case |", "|---|---|---|"]
    for n, b in SYSTEM_BUILDERS.items():
        ch = diff(a, b())
        o.append(f"| {n} | {SYSTEM_DESCRIPTIONS[n]} | " + ("—" if not ch else "; ".join(
            f"`{p_}` {_fmtv(x)} → {_fmtv(y)}" for p_, x, y in ch)) + " |")
    o += ["", "## 3. The engine", "",
          "One calculation graph (`aurelia/model/engine.py`) of 13 nodes produces every number in the app. Each node "
          "declares the line items it reads and produces, with a plain-language formula, and the graph is evaluated "
          "in dependency order once per scenario. Room demand is simulated daily; everything else monthly over 36 "
          "months. Results are cached by the exact assumption set, and scenarios store complete assumption trees "
          "(including the random seed), so a scenario always reproduces exactly. See "
          "[CALCULATION_REFERENCE_GENERATED.md](CALCULATION_REFERENCE_GENERATED.md) for every formula and "
          "[CALCULATIONS_AND_ASSUMPTIONS.md](CALCULATIONS_AND_ASSUMPTIONS.md) for conventions.", "",
          "## 4. Modelling Workbench models", "", "| Model | Name | What it shows |", "|---|---|---|"]
    o += [f"| {c} | {t} | {d_} |" for c, t, d_ in MODELS]
    o += ["", "All eight are views of the same engine output; none is a separate shortcut model.", "",
          "## 5. Executive Decision Room cases", "",
          "Every option is a documented change to an assumption set; its effect is the engine result with the change "
          "minus the result without it, over the case's analysis window. *Strongest option* is the one an experienced "
          "analyst would most likely recommend; other options can be defensible under stated conditions.", "",
          "| Case | Category | Decision metric | Options | Strongest option |", "|---|---|---|---|---|"]
    for c in D.CASES:
        best = max(c.options, key=lambda x: x.quality)
        o.append(f"| {c.title} | {c.category} | {D.metric_label(c)} | {len(c.options)} | {best.label} |")
    o += ["", "## 6. Investment cases", "", "| Case | Type | Description | Key parameters (defaults) |",
          "|---|---|---|---|"]
    for c in inv.CASES:
        ps = "; ".join(f"{p_.label} {_fmtv(p_.value)}" for p_ in c.params)
        o.append(f"| {c.title} | {c.category} | {c.description} | {ps} |")
    o += ["", "## 7. Learning path", "", "| Stage | Topic | Competency | Applied task |", "|---|---|---|---|"]
    for t in topics():
        o.append(f"| {t.stage}. {STAGES[t.stage]} | {t.title} | {COMPETENCIES[t.competency]} | {t.applied.kind} |")
    o += ["", "Competencies assessed: " + "; ".join(COMPETENCIES.values()) + ".", ""]
    p = ROOT / "docs" / "MODEL_REFERENCE.md"
    p.write_text("\n".join(o), encoding="utf-8")
    return p


def _fmtv(v) -> str:
    if isinstance(v, float):
        return f"{v:,.4g}" if abs(v) < 1000 else f"{v:,.0f}"
    return str(v)


if __name__ == "__main__":
    print(main())
    print(glossary())
    print(model_reference())
