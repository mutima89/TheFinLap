"""Formatted Excel exports of model outputs (statements, variance tables, any DataFrame).

Exports contain values (not live formulas) because they are snapshots of the
engine's results; each file records the scenario, timestamp and app version so it
can be reproduced.
"""
from __future__ import annotations

import datetime as dt
from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.styles import Alignment, Font, PatternFill, Border, Side

from .. import __version__
from ..analysis import statements as stm

HEAD = PatternFill("solid", fgColor="1F2A44")
SUB = PatternFill("solid", fgColor="E8EBF2")
WHITE_BOLD = Font(bold=True, color="FFFFFF")
TOP = Border(top=Side(style="thin", color="7F7F7F"))
NOTE = ("Fictional training data generated by Aurelia Finance Lab for The Aurelia Grand. Not real hotel data and "
        "not an industry benchmark.")


def _sheet_from_frame(wb: Workbook, title: str, df: pd.DataFrame, heading: str, meta: str,
                      money_fmt: str = "#,##0;[Red](#,##0)", pct_cols: tuple[str, ...] = (),
                      style_col: str | None = None, first: bool = False) -> None:
    ws = wb.active if first else wb.create_sheet()
    ws.title = title[:31]
    ws["A1"] = heading
    ws["A1"].font = Font(bold=True, size=13)
    ws["A2"] = meta
    ws["A2"].font = Font(italic=True, color="7F7F7F")
    styles = list(df[style_col]) if style_col and style_col in df.columns else None
    view = df.drop(columns=[c for c in ("style", "key") if c in df.columns])
    for j, c in enumerate(view.columns, 1):
        cell = ws.cell(row=4, column=j, value=str(c))
        cell.fill, cell.font = HEAD, WHITE_BOLD
        cell.alignment = Alignment(horizontal="center")
    for i, row in enumerate(view.itertuples(index=False), 5):
        st = styles[i - 5] if styles else None
        for j, v in enumerate(row, 1):
            if isinstance(v, float) and pd.isna(v):
                v = None
            cell = ws.cell(row=i, column=j, value=v)
            col = view.columns[j - 1]
            if isinstance(v, (int, float)) and not isinstance(v, bool):
                cell.number_format = "0.0%" if col in pct_cols else (
                    "#,##0.00" if abs(v) < 1000 and money_fmt.startswith("#,##0;") else money_fmt)
            if st in ("b", "h"):
                cell.font = Font(bold=True)
                if st == "b":
                    cell.border = TOP
            if st == "h":
                cell.fill = SUB
            if j == 1 and st == "i":
                cell.alignment = Alignment(indent=2)
    ws.column_dimensions["A"].width = max(28, min(48, int(view.iloc[:, 0].astype(str).str.len().max() + 4))) \
        if len(view) else 28
    for j in range(2, len(view.columns) + 1):
        ws.column_dimensions[ws.cell(row=4, column=j).column_letter].width = 15
    ws.freeze_panes = "B5"
    ws.sheet_view.showGridLines = False


def _meta(scenario: str, currency: str) -> str:
    return (f"Scenario: {scenario} · Currency: {currency} (excl. VAT) · Exported "
            f"{dt.datetime.now():%Y-%m-%d %H:%M} · Aurelia Finance Lab {__version__}")


def export_statements(result, path: str | Path, scenario: str = "", currency: str = "SAR", fx: float = 1.0,
                      freq: str = "annual") -> Path:
    path = Path(path)
    frames = {"Operating statement": stm.operating_statement(result, freq),
              "Income statement": stm.income_statement(result, freq),
              "Balance sheet": stm.balance_sheet(result, freq),
              "Cash flow": stm.cash_flow_statement(result, freq),
              "Revenue to cash": stm.revenue_cash_bridge(result, freq)}
    wb = Workbook()
    meta = _meta(scenario, currency)
    for i, (name, df) in enumerate(frames.items()):
        df = df.copy()
        num = [c for c in df.columns if c not in ("Line", "style", "key")]
        df[num] = df[num].astype(float) * fx
        _sheet_from_frame(wb, name, df, f"The Aurelia Grand — {name}", meta, style_col="style", first=(i == 0))
    chk = stm.checks_frame(result)
    _sheet_from_frame(wb, "Integrity checks", chk, "Integrity checks", meta, money_fmt="0.000000")
    ws = wb.create_sheet("About")
    for r, t in enumerate([NOTE, "Values are a snapshot of the simulation engine's output, not live formulas.",
                           "Reproduce: open the same scenario in Aurelia Finance Lab and export again."], 1):
        ws.cell(row=r, column=1, value=t)
    ws.column_dimensions["A"].width = 110
    wb.save(path)
    return path


def export_frames(frames: dict[str, pd.DataFrame], path: str | Path, title: str, scenario: str = "",
                  currency: str = "SAR", pct_cols: tuple[str, ...] = ()) -> Path:
    path = Path(path)
    wb = Workbook()
    meta = _meta(scenario, currency)
    for i, (name, df) in enumerate(frames.items()):
        _sheet_from_frame(wb, name, df, f"{title} — {name}", meta, pct_cols=pct_cols, first=(i == 0))
    ws = wb.create_sheet("About")
    ws["A1"] = NOTE
    ws.column_dimensions["A"].width = 110
    wb.save(path)
    return path
