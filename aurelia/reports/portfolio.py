"""Exportable learning portfolio (HTML/PDF + JSON).

Collects the learner's completed analysis, model outputs, assumptions, decision
rationale and assessment results from the local database. Nothing is uploaded.
"""
from __future__ import annotations

import datetime as dt
import html
import json
from pathlib import Path

from .. import __version__
from ..analysis import decisions as D
from ..learning import progress as P
from ..learning.content import topics
from ..model.assumptions import baseline, diff, SPEC_BY_PATH
from .management_report import CSS

DISCLAIMER = ("This portfolio documents practice work in Aurelia Finance Lab, an offline training simulator using "
              "fictional data for a fictional hotel. Scores and competency levels are practice feedback generated by "
              "the application. They are not an accredited qualification, certification or guarantee of "
              "employment.")


def _e(s) -> str:
    return html.escape(str(s))


def collect(db, state=None) -> dict:
    data: dict = {"generated": dt.datetime.now().isoformat(timespec="seconds"), "app_version": __version__,
                  "disclaimer": DISCLAIMER}
    data["competencies"] = [vars(c) for c in P.competency_profile(db)]
    prog = {r["topic_id"]: dict(r) for r in db.query("SELECT * FROM progress")}
    data["topics"] = [{"id": t.id, "stage": t.stage, "title": t.title,
                       "status": prog.get(t.id, {}).get("status", "not started"),
                       "best": prog.get(t.id, {}).get("best_score", 0)} for t in topics()]
    data["workbooks"] = [dict(ts=r["ts"], workbook=r["workbook"], file=r["file_name"], score=r["score"])
                         for r in db.query("SELECT * FROM workbook_grades ORDER BY id")]
    decs = []
    for r in db.query("SELECT * FROM decisions ORDER BY id"):
        c = D.CASE_BY_ID.get(r["case_id"])
        s = json.loads(r["scores"])
        opt = next((o.label for o in c.options if o.id == r["option_id"]), r["option_id"]) if c else r["option_id"]
        decs.append({"ts": r["ts"], "case": c.title if c else r["case_id"], "option": opt,
                     "justification": r["justification"], "overall": s.get("overall"),
                     "dimensions": s.get("dimensions", {}), "estimate": s.get("estimate"), "truth": s.get("truth"),
                     "realised": s.get("realised")})
    data["decisions"] = decs
    data["capstone"] = [{"step": int(r["step"]), "score": r["score"], **json.loads(r["data"] or "{}")}
                        for r in db.query("SELECT * FROM capstone ORDER BY CAST(step AS INTEGER)")]
    data["action_plans"] = [dict(r) for r in db.query("SELECT * FROM action_plans ORDER BY due_date")]
    data["forecast_versions"] = [{k: r[k] for k in ("created_at", "name", "scenario_name", "status", "approved_by")}
                                 for r in db.query("SELECT * FROM forecast_versions ORDER BY id")]
    scen = []
    b = baseline()
    for r in db.query("SELECT * FROM scenarios WHERE kind = 'user' ORDER BY id"):
        a = json.loads(r["assumptions"])
        ch = diff(b, a)
        scen.append({"name": r["name"], "description": r["description"], "changes": [
            {"driver": SPEC_BY_PATH[p].label if p in SPEC_BY_PATH else p, "baseline": o, "scenario": n}
            for p, o, n in ch[:40]]})
    data["scenarios"] = scen
    if state is not None:
        res = state.result
        k = res.kpis(res.year_slice(1))
        data["current_scenario"] = {"name": state.scenario_name, "year1": {
            "Occupancy": f"{(k['occupancy'] or 0) * 100:.1f}%", "ADR": state.money(k["adr"]),
            "RevPAR": state.money(k["revpar"]), "Total revenue": state.money(k["total_revenue"]),
            "GOP margin": f"{(k['gop_margin'] or 0) * 100:.1f}%", "EBITDA": state.money(k["ebitda"]),
            "Closing cash": state.money(k["closing_cash"])},
            "checks_passed": res.all_checks_passed}
    return data


def to_html(data: dict, learner: str = "") -> str:
    p = [f"<html><head><meta charset='utf-8'><title>Aurelia Finance Lab portfolio</title><style>{CSS}</style>"
         "</head><body>",
         f"<h1>Commercial Finance Practice Portfolio</h1><div class='meta'>{_e(learner) + ' · ' if learner else ''}"
         f"Generated {data['generated'][:10]} · Aurelia Finance Lab {data['app_version']}</div>",
         f"<div class='box'>{_e(DISCLAIMER)}</div>"]
    p.append("<h2>Competency profile</h2><table><tr><th>Competency</th><th>Level</th><th>Weighted score</th>"
             "<th>Practical passes</th><th>Hint-free</th><th>Recurring mistakes</th></tr>")
    for c in data["competencies"]:
        p.append(f"<tr><td>{_e(c['label'])}</td><td>{_e(c['level'])}</td><td>{c['score'] * 100:.0f}%</td>"
                 f"<td>{c['practical_passes']}</td><td>{'yes' if c['independent'] else 'no'}</td><td>"
                 f"{_e(', '.join(f'{m} ×{n}' for m, n in c['recurring_mistakes']) or '—')}</td></tr>")
    p.append("</table>")
    done = [t for t in data["topics"] if t["status"] == "completed"]
    p.append(f"<h2>Learning path</h2><p>{len(done)} of {len(data['topics'])} topics completed.</p><ul>" +
             "".join(f"<li>Stage {t['stage']}: {_e(t['title'])}</li>" for t in done) + "</ul>")
    if "current_scenario" in data:
        cs = data["current_scenario"]
        p.append(f"<h2>Model outputs — scenario '{_e(cs['name'])}' (year 1)</h2><table>" +
                 "".join(f"<tr><td>{_e(k)}</td><td style='text-align:right'>{_e(v)}</td></tr>"
                         for k, v in cs["year1"].items()) +
                 f"</table><p class='small'>Integrity checks {'all passed' if cs['checks_passed'] else 'FAILED'}.</p>")
    if data["scenarios"]:
        p.append("<h2>Scenarios and assumptions</h2>")
        for s in data["scenarios"]:
            p.append(f"<p><b>{_e(s['name'])}</b> {_e(s['description'] or '')}</p><table><tr><th>Driver</th>"
                     "<th>Baseline</th><th>Scenario</th></tr>" +
                     "".join(f"<tr><td>{_e(c['driver'])}</td><td>{_e(c['baseline'])}</td><td>{_e(c['scenario'])}"
                             f"</td></tr>" for c in s["changes"]) + "</table>")
    if data["decisions"]:
        p.append("<h2>Decision rationale</h2>")
        for d in data["decisions"]:
            dims = ", ".join(f"{D.DIMENSION_LABELS.get(k, k)} {v * 100:.0f}%" for k, v in d["dimensions"].items())
            p.append(f"<p><b>{_e(d['case'])}</b> — chose <i>{_e(d['option'])}</i> · score {d['overall']:.0f} "
                     f"({_e(dims)})</p><div class='box'>{_e(d['justification'])}</div>")
    if data["workbooks"]:
        p.append("<h2>Excel workbooks</h2><table><tr><th>Date</th><th>Workbook</th><th>Score</th></tr>" +
                 "".join(f"<tr><td>{_e(w['ts'][:10])}</td><td>{_e(w['workbook'])}</td><td>{w['score']:.1f}%</td></tr>"
                         for w in data["workbooks"]) + "</table>")
    if data["capstone"]:
        p.append("<h2>Capstone</h2><table><tr><th>Step</th><th>Score</th></tr>" +
                 "".join(f"<tr><td>{c['step']}</td><td>{c['score'] * 100:.0f}%</td></tr>" for c in data["capstone"]) +
                 "</table>")
        rec = next((c for c in data["capstone"] if c["step"] == 9), None)
        if rec and rec.get("answers", {}).get("text"):
            p.append(f"<h3>Executive recommendation</h3><div class='box'>{_e(rec['answers']['text'])}</div>")
    if data["action_plans"]:
        p.append("<h2>Action plans</h2><table><tr><th>Action</th><th>Owner</th><th>Due</th><th>Status</th></tr>" +
                 "".join(f"<tr><td>{_e(a['title'])}</td><td>{_e(a['owner'])}</td><td>{_e(a['due_date'])}</td>"
                         f"<td>{_e(a['status'])}</td></tr>" for a in data["action_plans"]) + "</table>")
    if data["forecast_versions"]:
        p.append("<h2>Forecast versions</h2><table><tr><th>Created</th><th>Name</th><th>Status</th><th>Approved by"
                 "</th></tr>" + "".join(f"<tr><td>{_e(v['created_at'][:10])}</td><td>{_e(v['name'])}</td><td>"
                                        f"{_e(v['status'])}</td><td>{_e(v['approved_by'] or '')}</td></tr>"
                                        for v in data["forecast_versions"]) + "</table>")
    p.append(f"<p class='small'>{_e(DISCLAIMER)}</p></body></html>")
    return "\n".join(p)


def export(db, out_dir: str | Path, state=None, learner: str = "", pdf: bool = True) -> list[Path]:
    from ..excel.workbooks import unique_path
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    data = collect(db, state)
    stem = f"Aurelia_portfolio_{dt.date.today():%Y%m%d}"
    h = to_html(data, learner)
    paths = []
    hp = unique_path(out / f"{stem}.html")
    hp.write_text(h, encoding="utf-8")
    paths.append(hp)
    jp = unique_path(out / f"{stem}.json")
    jp.write_text(json.dumps(data, indent=2, default=str), encoding="utf-8")
    paths.append(jp)
    if pdf:
        from .management_report import save_pdf
        paths.append(save_pdf(h, unique_path(out / f"{stem}.pdf")))
    return paths
