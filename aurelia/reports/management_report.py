def build_report(fpa: FPAData, actions: list[Action] | None = None, money: Callable[[float], str] | None = None,
                 budget_name: str = "Base case", forecast_name: str = "Working forecast",
                 prepared_by: str = "", period: str = "ytd", currency: str = "SAR", fx: float = 1.0) -> str:
    money = money or (lambda v: f"{currency} {v * fx:,.0f}")

    def k(v: float) -> str:  # table cells: thousands, negatives in brackets
        x = v * fx / 1000
        return f"({abs(x):,.0f})" if x < -0.5 else f"{x:,.0f}"
    unit = f"{currency} '000"
    actions = list(actions or [])
    A, B = fpa.actual, fpa.budget
    m = fpa.as_of
    month_label = str(A.months[m - 1])
    ytd = fpa.ytd_slice()
    vt = fpa.variance_table(period)
    vti = vt.set_index("key")
    vt_f = fpa.variance_table(period, compare="forecast").set_index("key")
    material = vt[vt["Material"] == "Yes"]
    expl = fpa.explanations(period)

    def tot(res, k, sl=ytd):
        return float(res.s(k)[sl].sum())

    occ_a, occ_b = (safe_div(tot(r, "occupied_rooms"), tot(r, "available_rooms")) for r in (A, B))
    adr_a, adr_b = (safe_div(tot(r, "rooms_revenue"), tot(r, "occupied_rooms")) for r in (A, B))
    rr = {k: fpa.run_rate(k) for k in ("total_revenue", "ebitda", "gop")}
    e_var = vti.at["ebitda", "Variance"]
    rev_var = vti.at["total_revenue", "Variance"]
    le_gap = rr["ebitda"]["latest_estimate"] - rr["ebitda"]["budget"]
    cash_a, cash_b = float(A.s("cash")[m - 1]), float(B.s("cash")[m - 1])
    min_cash = float(A.assumptions["financing"].get("minimum_cash", 0))

    parts = [f"<html><head><meta charset='utf-8'><title>Management report {month_label}</title>"
             f"<style>{CSS}</style></head><body>",
             "<h1>The Aurelia Grand — Monthly Management Report</h1>",
             f"<div class='meta'>Period: year to date to {_e(month_label)} ({m} months) · Budget: {_e(budget_name)}"
             f" · Forecast: {_e(forecast_name)} · Prepared {dt.date.today():%d %b %Y}"
             f"{' by ' + _e(prepared_by) if prepared_by else ''} · Aurelia Finance Lab {__version__}</div>",
             f"<div class='small'>{_e(NOTE)}</div>"]

    # 1 ------------------------------------------------------------------------------------------------
    occ_word = "above" if occ_a >= occ_b else "below"
    ebitda_word = "above" if e_var >= 0 else "below"
    bullets = [
        f"Occupancy {occ_a * 100:.1f}% vs {occ_b * 100:.1f}% budget ({occ_word}); ADR {money(adr_a)} vs "
        f"{money(adr_b)}.",
        f"Total revenue {money(tot(A, 'total_revenue'))}, {money(rev_var)} vs budget "
        f"({vti.at['total_revenue', 'Variance %'] * 100:+.1f}%).",
        f"EBITDA {money(tot(A, 'ebitda'))}, {money(e_var)} vs budget "
        f"({vti.at['ebitda', 'Variance %'] * 100:+.1f}%) — {ebitda_word} budget.",
        f"Latest estimate for the full year: EBITDA {money(rr['ebitda']['latest_estimate'])} vs budget "
        f"{money(rr['ebitda']['budget'])} (gap {money(le_gap)}).",
        f"Closing cash {money(cash_a)} vs {money(cash_b)} budget; operating cash flow variance "
        f"{money(vti.at['cfo', 'Variance'])}.",
        f"{len(material)} line(s) breach the materiality threshold ({money(fpa.materiality.absolute)} and "
        f"{fpa.materiality.percent * 100:.0f}%).",
    ]
    headline = ""
    if occ_a >= occ_b and e_var < 0:
        headline = ("<div class='box'><b>Key message:</b> the hotel is busier than budget but less profitable. "
                    "Volume is not the problem; the variance sits in rate/mix, distribution cost and cost control. "
                    "See sections 3–4.</div>")
    parts.append("<h2>1. Executive summary</h2>" + headline + "<ul>" +
                 "".join(f"<li>{_e(b)}</li>" for b in bullets) + "</ul>")

    # 2 ------------------------------------------------------------------------------------------------
    keys = ["rooms_revenue", "fnb_revenue", "spa_revenue", "events_revenue", "total_revenue", "total_dept_profit",
            "gop", "ebitda", "cfo"]
    rows, cls = [], []
    for key in keys:
        a_, b_ = vti.at[key, "Actual"], vti.at[key, "Budget"]
        f_ = vt_f.at[key, "Forecast"]
        rows.append([_e(vti.at[key, "Line"]), k(a_), k(b_), k(a_ - b_),
                     f"<span class='{vti.at[key, 'F/U']}'>{_e(vti.at[key, 'F/U'])}</span>", k(f_), k(a_ - f_),
                     k(fpa.le(key).sum()), k(float(B.s(key)[:12].sum()))])
        cls.append("b" if key in ("total_revenue", "gop", "ebitda") else "")
    parts.append("<h2>2. Actual, budget and forecast</h2>" +
                 f"<div class='small'>{unit}</div>" +
                 _table(["Line (YTD)", "Actual", "Budget", "Var vs budget", "F/U", "Forecast", "Var vs forecast",
                         "FY latest estimate", "FY budget"], rows, classes=cls) +
                 "<div class='small'>Latest estimate = actuals to the close month plus the working forecast for the "
                 "remaining months. Forecast here is the working scenario, a set of assumptions — not a prediction."
                 "</div>")

    # 3 ------------------------------------------------------------------------------------------------
    rows = [[_e(r["Line"]), k(r["Actual"]), k(r["Budget"]), k(r["Variance"]),
             f"{r['Variance %'] * 100:+.1f}%" if r["Variance %"] == r["Variance %"] else "n/a",
             f"<span class='{r['F/U']}'>{_e(r['F/U'])}</span>", _e(r["Context"])]
            for _, r in material.iterrows()]
    parts.append("<h2>3. Material variances</h2>" +
                 (f"<div class='small'>{unit}</div>" +
                  _table(["Line", "Actual", "Budget", "Variance", "%", "F/U", "Classification basis"], rows)
                  if rows else "<p>No variance breaches the materiality threshold.</p>"))

    # 4 ------------------------------------------------------------------------------------------------
    blocks = []
    for x in expl:
        ev = "".join(f"<li>{_e(s)}</li>" for s in x["evidence"])
        tc = "".join(f"<li>{_e(s)}</li>" for s in x["to_confirm"])
        blocks.append(f"<p><b>{_e(x['line'])}</b> — {money(x['variance'])} "
                      f"(<span class='{x['fu']}'>{_e(x['fu'])}</span>)</p>"
                      f"<div class='small'>Quantified by the data:</div><ul>{ev}</ul>" +
                      (f"<div class='small'>Possible causes to confirm (not established by the data):</div>"
                       f"<ul>{tc}</ul>" if tc else ""))
    parts.append("<h2>4. Evidence-supported explanations</h2>" + ("".join(blocks) or "<p>None required.</p>") +
                 ("<div class='small'>Figures inside explanations are in SAR.</div>" if currency != "SAR" else "") +
                 "<div class='small'>Driver attributions are arithmetic decompositions of the variance. They "
                 "show where the money went, not why; causes are listed separately until confirmed.</div>")

    # 5 ------------------------------------------------------------------------------------------------
    risks = []
    if le_gap < 0:
        risks.append(f"Full-year EBITDA latest estimate is {money(-le_gap)} below budget; run-rate EBITDA "
                     f"{money(rr['ebitda']['run_rate_fy'])}.")
    rf = fpa.rolling_forecast(12)
    if len(rf):
        low = rf["Closing cash"].min()
        if low < min_cash * 1.2:
            risks.append(f"Forecast closing cash falls to {money(low)}, close to the minimum cash policy of "
                         f"{money(min_cash)}; revolver drawings likely.")
        else:
            risks.append(f"Lowest forecast month-end cash over the next 12 months: {money(low)} "
                         f"(minimum policy {money(min_cash)}).")
    dso_a = A.assumptions["working_capital"]["dso_days"]
    dso_b = B.assumptions["working_capital"]["dso_days"]
    if dso_a > dso_b:
        risks.append(f"Collection days are running at {dso_a:.0f} vs {dso_b:.0f} budgeted, tying up cash in "
                     "receivables; bad-debt exposure rises with age.")
    ota_a = safe_div(float(A.segments["leisure_ota"]["room_nights"][ytd].sum()), tot(A, "occupied_rooms"))
    ota_b = safe_div(float(B.segments["leisure_ota"]["room_nights"][ytd].sum()), tot(B, "occupied_rooms"))
    if ota_a > ota_b + 0.01:
        risks.append(f"OTA share {ota_a * 100:.1f}% vs {ota_b * 100:.1f}% budget: dependence on a costly channel "
                     "reduces net ADR if it persists.")
    if "fnb_cogs" in set(material["key"]):
        risks.append("F&B cost ratio above budget: if not corrected it compounds through the high season.")
    risks.append("These are risks to monitor based on current assumptions; the model does not predict outcomes.")
    parts.append("<h2>5. Forward-looking risks</h2><ul>" + "".join(f"<li>{_e(r)}</li>" for r in risks) + "</ul>")

    # 6 + 7 ------------------------------------------------------------------------------------------------
    recorded = [a for a in actions if not a.proposed]
    proposed = []
    covered = {a.variance_ref for a in recorded}
    due = (dt.date(A.months[m - 1].year, A.months[m - 1].month, 1) + dt.timedelta(days=62)).replace(day=1) \
        - dt.timedelta(days=1)
    for _, r in material.iterrows():
        k = r["key"]
        if k in SUGGESTED and r["F/U"] == "U" and k not in covered and r["Line"] not in covered:
            t, role = SUGGESTED[k]
            proposed.append(Action(t, role, due.isoformat(), "Proposed", r["Line"], True))
    recs = recorded + proposed
    parts.append("<h2>6. Recommended corrective actions</h2>" + (
        "<ol>" + "".join(f"<li>{_e(a.title)}{' <span class=tag>proposed</span>' if a.proposed else ''}"
                         f"{' — addresses ' + _e(a.variance_ref) if a.variance_ref else ''}</li>" for a in recs) +
        "</ol>" if recs else "<p>No corrective actions required.</p>"))
    rows = [[_e(a.title), _e(a.owner) + (" <span class='tag'>role – assign a name</span>" if a.proposed else ""),
             _e(a.due_date), _e(a.status)] for a in recs]
    parts.append("<h2>7. Action owners and due dates</h2>" +
                 (_table(["Action", "Owner", "Due", "Status"], rows, right_from=99) if rows else
                  "<p>No actions recorded. Add them in FP&amp;A Lab → Action plans.</p>") +
                 ("<div class='small'>Proposed actions carry a role, not a person: assign a named owner in the FP&amp;A "
                  "Lab before circulating this report.</div>" if proposed else ""))
    parts.append(f"<p class='small'>Reproducible: same scenarios, close month {m} and materiality settings give the "
                 f"same report. {_e(NOTE)}</p></body></html>")
    return "\n".join(parts)


def save_html(html_text: str, path: str | Path) -> Path:
    path = Path(path)
    path.write_text(html_text, encoding="utf-8")
    return path


def save_pdf(html_text: str, path: str | Path) -> Path:
    """Render HTML to PDF with Qt (requires a QGuiApplication)."""
    from PySide6.QtGui import QTextDocument, QPdfWriter, QPageSize, QPageLayout
    from PySide6.QtCore import QMarginsF
    path = Path(path)
    writer = QPdfWriter(str(path))
    writer.setPageSize(QPageSize(QPageSize.A4))
    writer.setPageLayout(QPageLayout(QPageSize(QPageSize.A4), QPageLayout.Portrait, QMarginsF(12, 12, 12, 12),
                                     QPageLayout.Millimeter))
    writer.setResolution(110)
    doc = QTextDocument()
    doc.setDefaultStyleSheet(CSS)
    doc.setHtml(html_text)
    doc.setPageSize(writer.pageLayout().paintRectPixels(writer.resolution()).size().toSizeF())
    doc.print_(writer)
    return path


def actions_from_db(db) -> list[Action]:
    return [Action(r["title"], r["owner"], r["due_date"], r["status"], r["variance_ref"] or "")
            for r in db.query("SELECT * FROM action_plans WHERE status != 'Cancelled' ORDER BY due_date")]
