NOTE = ("Fictional training data for The Aurelia Grand, generated by Aurelia Finance Lab. Not real hotel data, "
        "not an industry benchmark and not a prediction.")

# Proposed actions for material variances when the user has not recorded their own.
SUGGESTED = {
    "rooms_revenue": ("Review segment mix and rate strategy for the next 90 days", "Director of Revenue"),
    "commissions": ("Review OTA promotion terms and the direct-booking incentive", "Director of Revenue"),
    "fnb_cogs": ("Stock count, waste log review and menu-engineering of the top 20 items", "Director of F&B"),
    "fnb_labour": ("Re-base the F&B rota to forecast covers; approve overtime in advance", "Director of F&B"),
    "spa_revenue": ("Test in-stay spa offers and review online booking friction", "Spa Manager"),
    "sm_expense": ("Post-campaign ROI review before any further unbudgeted spend", "Director of Sales & Marketing"),
    "utilities_expense": ("Review energy tariff and consumption by plant item", "Chief Engineer"),
    "cfo": ("Aged-debtors review; enforce credit terms on corporate and group accounts", "Financial Controller"),
    "ebitda": ("Agree a recovery plan across the departments driving the EBITDA gap", "General Manager"),
    "gop": ("Departmental cost review against flexed budgets", "Hotel Manager"),
}


@dataclass
class Action:
    title: str
    owner: str
    due_date: str
    status: str = "Open"
    variance_ref: str = ""
    proposed: bool = False


def _e(s) -> str:
    return html.escape(str(s))


def _table(headers: list[str], rows: list[list], right_from: int = 1, classes: list[str] | None = None) -> str:
    h = "".join(f"<th style='text-align:{'left' if i < right_from else 'right'}'>{_e(x)}</th>"
                for i, x in enumerate(headers))
    body = []
    for k, r in enumerate(rows):
        cls = f" class='{classes[k]}'" if classes and classes[k] else ""
        tds = "".join(f"<td style='text-align:{'left' if i < right_from else 'right'}'>{x}</td>"
                      for i, x in enumerate(r))
        body.append(f"<tr{cls}>{tds}</tr>")
    return f"<table><thead><tr>{h}</tr></thead><tbody>{''.join(body)}</tbody></table>"


