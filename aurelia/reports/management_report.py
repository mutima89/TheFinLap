"""Monthly management performance report (HTML, optionally PDF).

Sections (as required by the FP&A brief):
  1. Executive summary
  2. Actual, budget and forecast
  3. Material variances
  4. Evidence-supported explanations
  5. Forward-looking risks
  6. Recommended corrective actions
  7. Named action owners and due dates

Every number comes from :mod:`aurelia.analysis.fpa` (the engine). Explanations keep
the distinction between what the data quantifies and what still needs confirmation;
residuals the drivers cannot explain are labelled as unexplained.
"""
from __future__ import annotations

import datetime as dt
import html
from dataclasses import dataclass
from pathlib import Path
from typing import Callable

from .. import __version__
from ..analysis.fpa import FPAData
