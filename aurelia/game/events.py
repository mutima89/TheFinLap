"""Briefing cards for Season mode: market news, decisions and operational issues.

Every hotel, company and event here is FICTIONAL, and every number is a training assumption generated by the
simulator, not a benchmark. A card turns a player's choice into an ``Outcome``: an ``effect`` (changes applied to
the month's assumption tree before the engine runs, see ``season.apply_effect``) plus score and story consequences.

Effect keys (all optional):
    seg_demand   {segment: multiplier}        base demand for the month
    seg_rate     {segment: multiplier}        published rate for the month
    seg_discount {segment: added discount}    e.g. an OTA promotion
    events       [{name, start_day, end_day, multiplier}]   all-segment demand compression on those days
    group_blocks [{day, nights, rooms, rate, fnb}]           contracted block starting on that day of the month
    one_off      SAR                          one-off operating cost charged this month
    ooo_rooms    rooms                        rooms out of order for the whole month
    fnb_cogs     added food cost %            e.g. a supplier price rise
"""
from __future__ import annotations

import random
from dataclasses import dataclass, field
from typing import Callable

SHOULDER = (3, 4, 9, 10)
SUMMER = (5, 6, 7, 8)


@dataclass
class Choice:
    id: str
    label: str
    hint: str = ""


@dataclass
class Outcome:
    effect: dict = field(default_factory=dict)
    guest: float = 0.0          # immediate guest-score change
    confidence: int = 0         # immediate owner-confidence change
    carried: list = field(default_factory=list)     # [(tone, text)] shown at month close
    flags: dict = field(default_factory=dict)       # flags set on the season
    persistent: list = field(default_factory=list)  # [{"months": n, "effect": {...}, "label": str}] from next month
    risks: list = field(default_factory=list)       # [{"in": months ahead, "p": prob, "id", "title", "body", ...}]
    resolved: str = ""          # how an uncertain choice turned out (empty if certain)


@dataclass
class CardInstance:
    id: str
    kind: str                   # market | decision | issue | consequence
    source: str                 # who raises it, e.g. "Sales"
    title: str
    body: str
    choices: list[Choice] = field(default_factory=list)
    params: dict = field(default_factory=dict)

    def to_dict(self) -> dict:
        return {"id": self.id, "kind": self.kind, "source": self.source, "title": self.title, "body": self.body,
                "choices": [c.__dict__ for c in self.choices], "params": self.params}

    @property
    def default_choice(self) -> str | None:
        return self.choices[0].id if self.choices else None


@dataclass
class CardDef:
    id: str
    kind: str
    source: str
    months: tuple[int, ...]                     # months in which the card may appear
    weight: float
    make: Callable[[random.Random, int], dict]  # (rng, month) -> params
    title: Callable[[dict], str]
    body: Callable[[dict], str]
    choices: Callable[[dict], list[Choice]]
    resolve: Callable[[str, dict, random.Random], Outcome]
    requires: Callable[[dict], bool] = lambda flags: True
    once: bool = False                          # True: at most once per season

    def instance(self, rng: random.Random, month: int) -> CardInstance:
        p = self.make(rng, month)
        return CardInstance(self.id, self.kind, self.source, self.title(p), self.body(p), self.choices(p), p)


ALL = tuple(range(1, 13))


def _k(x: float) -> str:
    return f"SAR {x / 1000:,.0f}k"


def _none(_c, _p, _r) -> Outcome:
    return Outcome()


