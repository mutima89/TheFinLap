def _chiller_resolve(c, p, _r):
    if c == "repair":
        return Outcome(effect={"one_off": p["cost"]}, flags={"deferred": 0},
                       carried=[("good", "Chiller repaired: no risk of closing rooms this summer.")])
    return Outcome(flags={"deferred": 1}, risks=[{
        "in": 1, "p": 0.6, "id": "chiller_fail", "title": "The east-wing chiller failed",
        "body": f"{p['rooms']} rooms are closed for the month while it is replaced, at a cost of "
                f"{_k(p['cost'] * 1.6)}.",
        "effect": {"ooo_rooms": p["rooms"], "one_off": p["cost"] * 1.6}, "guest": -0.15, "confidence": -4}],
        carried=[("bad", "Chiller repair deferred: it may fail next month.")])


def _turnover_resolve(c, p, _r):
    if c == "agency":
        return Outcome(effect={"one_off": p["cost"]}, carried=[("info", "Agency staff covered housekeeping.")])
    return Outcome(guest=-0.2, carried=[("bad", "Rooms were turned late; guests noticed.")])


def _review_resolve(c, p, _r):
    if c == "recover":
        return Outcome(effect={"one_off": p["cost"]}, guest=0.08,
                       carried=[("good", "Service recovery calls turned most of those guests around.")])
    return Outcome(guest=-0.1, persistent=[{"months": 1, "effect": {"seg_demand": {"leisure_direct": 0.95,
                                                                                 "leisure_ota": 0.96}},
                                           "label": "Bad reviews"}],
                   carried=[("bad", "The reviews stay visible and may cost leisure bookings next month.")])


def _lift_resolve(c, p, _r):
    if c == "fix":
        return Outcome(effect={"one_off": p["cost"]}, carried=[("good", "Lifts modernised.")])
    return Outcome(effect={"one_off": p["patch"]}, flags={"deferred": 1}, risks=[{
        "in": 2, "p": 0.5, "id": "lift_fail", "title": "Lift breakdown during a busy week",
        "body": f"Guests were stuck on upper floors; emergency repair cost {_k(p['cost'] * 1.3)}.",
        "effect": {"one_off": p["cost"] * 1.3}, "guest": -0.2, "confidence": -3}],
        carried=[("bad", "The lift patch may not hold.")])


def _supplier_resolve(c, p, r):
    if c == "negotiate":
        if r.random() < 0.5:
            return Outcome(resolved="The supplier settled at half the increase.",
                           effect={"fnb_cogs": p["rise"] / 2},
                           persistent=[{"months": 11, "effect": {"fnb_cogs": p["rise"] / 2}, "label": "Food cost"}],
                           carried=[("good", "You halved the supplier's increase.")])
        return Outcome(resolved="The supplier would not move.", effect={"fnb_cogs": p["rise"]},
                       persistent=[{"months": 11, "effect": {"fnb_cogs": p["rise"]}, "label": "Food cost"}],
                       carried=[("bad", "The food price rise stands for the rest of the season.")])
    return Outcome(effect={"fnb_cogs": p["rise"]},
                   persistent=[{"months": 11, "effect": {"fnb_cogs": p["rise"]}, "label": "Food cost"}],
                   carried=[("info", "Food costs are higher for the rest of the season.")])


