class GlossaryPage(Page):
    def __init__(self, state):
        super().__init__("Glossary, Search and Help", "Search lessons, KPIs, drivers, models and decision cases.")
        self.state = state
        self.tabs = QTabWidget()
        self.body.addWidget(self.tabs, 1)
        w = QWidget()
        lay = QVBoxLayout(w)
        row = QHBoxLayout()
        self.q = QLineEdit()
        self.q.setPlaceholderText("e.g. RevPAR, flexible budget, displacement, DSO…")
        self.q.returnPressed.connect(self._search)
        row.addWidget(self.q, 1)
        row.addWidget(button("Search", self._search, primary=True))
        lay.addLayout(row)
        self.res = Table(min_height=380)
        self.res.doubleClicked.connect(self._open)
        lay.addWidget(self.res)
        lay.addWidget(label("Double-click a result to open it.", "Muted"))
        self.tabs.addTab(w, "Search")
        g = Table(min_height=500)
        g.set(pd.DataFrame([{"Term": k, "Definition": v} for k, v in sorted(GLOSSARY.items())]))
        g.setWordWrap(True)
        g.resizeRowsToContents()
        self.tabs.addTab(g, "Glossary")
        k = Table(min_height=500)
        k.set(pd.DataFrame([{"KPI": d.name, "Formula": d.formula, "Better when": d.nature.replace("_", " "),
                             "Notes": d.description} for d in KPI_DEFINITIONS.values()]))
        self.tabs.addTab(k, "KPI definitions")
        hb = QTextBrowser()
        sc = "".join(f"<tr><td><b>{a}</b></td><td>{b}</td></tr>" for a, b in SHORTCUTS)
        hb.setHtml(HELP + f"<h3>Keyboard shortcuts</h3><table>{sc}</table>"
                          f"<h3>Your data folder</h3><p>{app_data_dir()}</p>")
        self.tabs.addTab(hb, "Help")
        self._hits = []

    def _search(self):
        self._hits = search(self.q.text())
        self.res.set(pd.DataFrame([{"Type": h.kind, "Title": h.title, "Detail": h.snippet} for h in self._hits])
                     if self._hits else pd.DataFrame({"Type": [], "Title": [], "Detail": ["No matches."][:0]}))

    def _open(self, idx):
        h = self._hits[idx.row()]
        if h.page == "glossary":
            self.tabs.setCurrentIndex(1)
            return
        self.state.navigate.emit(h.page, h.payload)

    def focus_item(self, payload):
        if payload == "help":
            self.tabs.setCurrentIndex(3)
            return
        self.tabs.setCurrentIndex(0)
        self.q.setText(str(payload))
        self._search()
