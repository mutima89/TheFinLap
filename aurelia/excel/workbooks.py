"""Training workbooks: generation, task specifications and expected answers.

Each workbook has an ``Instructions`` tab, an ``Assumptions`` tab, one or more raw
data tabs and an exercise tab with yellow answer cells. The *reference* version of
each workbook contains the model answers as live formulas.

Expected answers are computed here in Python directly from the data written to the
workbook (never by reading the reference formulas back), so the tests can check the
reference formulas against an independent calculation.

All data is generated by the simulation engine for the fictional Aurelia Grand and
must not be read as industry benchmarks.
"""
