GREY = PatternFill("solid", fgColor="EDEDED")
WHITE_BOLD = Font(bold=True, color="FFFFFF")
BOLD = Font(bold=True)
THIN = Border(*(Side(style="thin", color="BFBFBF"),) * 4)
DISCLAIMER = ("Fictional training data generated by Aurelia Finance Lab for The Aurelia Grand. "
              "Not real hotel data and not an industry benchmark.")


@dataclass
class Task:
    id: str
    sheet: str
    cell: str
    title: str
    instruction: str
    reference: str                       # model-answer formula
    expected: float | str
    hint: str = ""
    functions_any: tuple[frozenset, ...] = ()   # at least one set must be fully used
    tolerance_abs: float = 0.01
    tolerance_rel: float = 1e-6
    mistakes: list[tuple[float | str, str]] = field(default_factory=list)
    points: float = 1.0
    concept: str = ""


@dataclass
class Reconciliation:
    name: str
    description: str
    check: Callable[[Callable[[str, str], object]], tuple[bool, str]]


@dataclass
class WorkbookSpec:
    key: str
    file_stem: str
    title: str
    objective: str
    build: Callable[[Workbook, bool], None]
    tasks: list[Task]
    reconciliations: list[Reconciliation] = field(default_factory=list)


# --------------------------------------------------------------------------- helpers
def _header(ws, row: int, values: list[str]) -> None:
    for i, v in enumerate(values, 1):
        c = ws.cell(row=row, column=i, value=v)
        c.fill, c.font, c.border = HEAD, WHITE_BOLD, THIN
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)


def _widths(ws, widths: dict[str, float]) -> None:
    for col, w in widths.items():
        ws.column_dimensions[col].width = w


def _instructions(wb: Workbook, spec_title: str, objective: str, steps: list[str], reference: bool) -> None:
    ws = wb.active
    ws.title = "Instructions"
    ws["A1"] = spec_title + (" — REFERENCE ANSWERS" if reference else "")
    ws["A1"].font = Font(bold=True, size=14)
    ws["A2"] = DISCLAIMER
    ws["A2"].font = Font(italic=True, color="7F7F7F")
    ws["A4"] = "Learning objective"
    ws["A4"].font = BOLD
    ws["A5"] = objective
    ws["A7"] = "How to work"
    ws["A7"].font = BOLD
    r = 8
    for i, s in enumerate(steps, 1):
        ws.cell(row=r, column=1, value=f"{i}. {s}")
        r += 1
    r += 1
    rules = ["Write formulas in the yellow cells on the Exercises tab. Do not type the answers as numbers: "
             "the grader checks both the value and that a formula produced it.",
             "Do not move, insert or delete rows or columns on any tab; the grader reads fixed cells.",
             "Save the file in Excel (.xlsx) so the calculated values are stored, then import it in "
             "Aurelia Finance Lab → Excel Lab → Grade a workbook. Aurelia grades a copy and never changes your file.",
             "Aurelia recalculates supported formulas itself because the openpyxl library reads formulas but does "
             "not calculate them. Unsupported functions are graded on Excel's saved value instead."]
    ws.cell(row=r, column=1, value="Rules").font = BOLD
    for s in rules:
        r += 1
        ws.cell(row=r, column=1, value="• " + s)
    ws.column_dimensions["A"].width = 130
    for row in ws.iter_rows(min_row=1, max_row=r):
        for c in row:
            c.alignment = Alignment(wrap_text=True, vertical="top")


def _exercise_sheet(wb: Workbook, tasks: list[Task], reference: bool, sheet: str = "Exercises",
                    title: str = "") -> None:
    ws = wb.create_sheet(sheet)
    ws["A1"] = title or "Exercises"
    ws["A1"].font = Font(bold=True, size=13)
    ws["A2"] = "Enter a formula in each yellow cell (column D)."
    _header(ws, 4, ["#", "Task", "What to calculate", "Your answer", "Hint"])
    _widths(ws, {"A": 6, "B": 30, "C": 70, "D": 18, "E": 60})
    for t in tasks:
        if t.sheet != sheet:
            continue
        row = int("".join(ch for ch in t.cell if ch.isdigit()))
        ws.cell(row=row, column=1, value=t.id)
        ws.cell(row=row, column=2, value=t.title)
        ws.cell(row=row, column=3, value=t.instruction).alignment = Alignment(wrap_text=True, vertical="top")
        c = ws[t.cell]
        c.fill, c.border = YELLOW, THIN
        if reference:
            c.value = t.reference
        ws.cell(row=row, column=5, value=t.hint).alignment = Alignment(wrap_text=True, vertical="top")


def _close(a: float, b: float, tol_abs: float, tol_rel: float) -> bool:
    return abs(a - b) <= max(tol_abs, tol_rel * abs(b))


# =========================================================================== 01 Revenue KPIs
def _revenue_data():
    r = simulate_cached(baseline())
    d = r.daily.iloc[:90].copy()  # Q1 of model year 1 (Jan–Mar 2027)
    channel = {"corporate": "Corporate contract", "leisure_direct": "Direct web", "leisure_ota": "OTA",
               "group": "Group desk", "wholesale": "Wholesale"}
    rows = []
    for _, x in d.iterrows():
        for s in SEGMENTS:
            rn = int(round(x[f"{s}_rooms"]))
            if rn <= 0:
                continue
            rate = round(float(x[f"{s}_rate"]), 2)
            rev = round(rn * rate, 2)
            comm_pct = float(x[f"{s}_commission"]) / float(x[f"{s}_revenue"]) if x[f"{s}_revenue"] else 0.0
            rows.append({"Date": x["date"].to_pydatetime(), "Segment": SEGMENT_LABELS[s], "Channel": channel[s],
                         "Room nights": rn, "Rate": rate, "Room revenue": rev,
                         "Commission": round(rev * comm_pct, 2),
                         "Cancelled RN": int(round(float(x[f"{s}_cancelled"])))})
    bookings = pd.DataFrame(rows)
    daily = pd.DataFrame({"Date": [t.to_pydatetime() for t in d["date"]],
                          "Available rooms": d["available"].round().astype(int).to_numpy()})
    occ = bookings.groupby("Date")["Room nights"].sum()
    daily["Occupied rooms"] = [int(occ.get(t, 0)) for t in daily["Date"]]
    daily["Room revenue"] = [round(float(bookings.loc[bookings["Date"] == t, "Room revenue"].sum()), 2)
                             for t in daily["Date"]]
    return bookings, daily


def _revenue_spec() -> WorkbookSpec:
    bookings, daily = _revenue_data()
    nb, nd = len(bookings) + 1, len(daily) + 1
    B = lambda col: f"Bookings!${col}$2:${col}${nb}"  # noqa: E731
    D = lambda col: f"Daily!${col}$2:${col}${nd}"  # noqa: E731
    rev = float(bookings["Room revenue"].sum())
    rn = float(bookings["Room nights"].sum())
    avail = float(daily["Available rooms"].sum())
    comm = float(bookings["Commission"].sum())
    feb = bookings[(bookings["Date"] >= dt.datetime(2027, 2, 1)) & (bookings["Date"] < dt.datetime(2027, 3, 1))]
    corp_feb = float(feb.loc[feb["Segment"] == SEGMENT_LABELS["corporate"], "Room revenue"].sum())
    ota_rn = float(bookings.loc[bookings["Channel"] == "OTA", "Room nights"].sum())
